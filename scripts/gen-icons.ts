const assets = resolve(dirname(createRequire(import.meta.url).resolve("@phosphor-icons/core/package.json")), "assets")

function body([name, weight = "regular", flip]: Entry): string {
  const file = resolve(assets, weight, weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`)
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(readFileSync(file, "utf8"))?.[1]
  if (!inner) throw new Error(`no phosphor icon named ${name} (${weight})`)
  return flip ? `<g transform="matrix(-1 0 0 1 256 0)">${inner}</g>` : inner
}

const rows = Object.entries(ICONS).map(([name, entry]) => {
  const id = name.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())
  return `export const ${id}Icon = ${JSON.stringify(body(entry))} as Glyph`
})

const out = `// Generated by scripts/gen-icons.ts. Do not edit.
// Glyphs from Phosphor Icons (@phosphor-icons/core), MIT License, Copyright (c) 2023 Phosphor Icons.
// One export per glyph, so a chunk carries only the glyphs it imports.

/** A glyph's svg body on a 256 unit grid, filled with the text color. */
export type Glyph = string & { readonly glyph: true }

${rows.join("\n")}
`
