const assets = resolve(import.meta.dirname, "cursor-icons")

function body(name: string): string {
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(readFileSync(resolve(assets, `${name}.svg`), "utf8"))?.[1]
  if (!inner) throw new Error(`no cursor icon named ${name}`)
  return inner
}

const rows = Object.entries(ICONS).map(([name, entry]) => {
  const id = name.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())
  return `export const ${id}Icon = ${JSON.stringify(body(entry))} as Glyph`
})

const out = `// Generated by scripts/gen-icons.ts. Do not edit.
// Glyphs from the Cursor icon set, drawn on a 300 unit grid.
// One export per glyph, so a chunk carries only the glyphs it imports.

/** A glyph's svg body on a 300 unit grid, filled with the text color. */
export type Glyph = string & { readonly glyph: true }

${rows.join("\n")}
`
writeFileSync(resolve(import.meta.dirname, "../packages/ui/src/icons.gen.ts"), out)
console.log(`wrote ${rows.length} icons`)
