export function macKeyCode(code: string, key: string): number {
  const mapped = CODES.get(code)
  if (mapped !== undefined) return mapped
  if (key.length !== 1) return 0xffff
  return CHARS.get(key.toUpperCase()) ?? CHARS.get(key) ?? 0xffff
}
