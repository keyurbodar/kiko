export function windowsVirtualKey(code: string, key: string): number {
  const letter = /^Key([A-Z])$/.exec(code)
  if (letter) return letter[1]!.charCodeAt(0)
  const digit = /^Digit([0-9])$/.exec(code)
  if (digit) return digit[1]!.charCodeAt(0)
  const fn = /^F([1-9]|1[0-9]|2[0-4])$/.exec(code)
  if (fn) return 0x70 + Number(fn[1]) - 1
  const mapped = VKCODE.get(code)
  if (mapped) return mapped
  const upper = key.length === 1 ? key.toUpperCase().charCodeAt(0) : 0
  return upper >= 0x20 && upper <= 0x7e ? upper : 0
}

