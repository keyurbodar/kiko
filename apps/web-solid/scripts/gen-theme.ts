// Writes the two files that follow `kat.css` and `src/theme/schema.ts`:
//   src/theme/known-tokens.ts  the variables a theme may set through `tokens`, with their kinds
//   docs/theming.md            every key, its variable, its range, and its default
//
//   bun run theme:gen          (in apps/web-solid)
//
// `theme.test.ts` rebuilds both in memory and fails when a file is stale, so the docs and
// the validator cannot drift from the CSS.

import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { FIELDS, GROUPS, PRESET_IDS, type Field } from "../src/theme/schema"
import { knownTokens, parseKat, ROOT } from "./theme-tokens"

export const TOKENS_FILE = join(ROOT, "apps/web-solid/src/theme/known-tokens.ts")
export const DOC_FILE = join(ROOT, "docs/theming.md")

export function buildTokensFile(css?: string): string {
  const rows = knownTokens(css).map((t) => `  ${JSON.stringify(t.name)}: ${JSON.stringify(t.kind)},`)
  return [
    "// Generated by `bun run theme:gen` from `packages/ui/src/styles/kat.css`. Do not edit.",
    "// Every custom property the theme `tokens` field may set, and what each one holds.",
    "",
    'export type TokenKind = "color" | "length" | "number" | "font" | "weight" | "any"',
    "",
    "export const KNOWN_TOKENS: Record<string, TokenKind> = {",
    ...rows,
    "}",
    "",
  ].join("\n")
}

const cell = (s: string) => s.replace(/\|/g, "\\|")

function range(f: Field): string {
  if (f.kind === "color") return "a CSS color"
  if (f.kind === "font") return "a font family list"
  if (f.kind === "weight") return `${f.min} to ${f.max}`
  if (f.kind === "length") return `${f.min}px to ${f.max}px`
  return `${f.min} to ${f.max}`
}

export function buildDoc(css?: string): string {
  const defaults = parseKat(css)
  const defaultOf = (f: Field) => (f.variable.endsWith("-scale") ? f.default! : (defaults.get(f.variable) ?? "not declared in kat.css"))
  const out: string[] = [
    "# Theming",
    "",
    "This file is generated by `bun run theme:gen` in `apps/web-solid`. Edit `src/theme/schema.ts` or `kat.css`, then regenerate. A test fails when it is stale.",
    "",
    "A theme is one JSON object. Every key maps to one CSS variable from `packages/ui/src/styles/tokens.md`. A key you leave out keeps the value from `extends`, so a two-line theme works.",
    "",
    "```json",
    '{ "version": 1, "name": "blue", "colors": { "accent": "oklch(0.7 0.14 250)" } }',
    "```",
    "",
    "## Top level",
    "",
    "| Key | Value |",
    "| --- | --- |",
    "| `version` | Required. Always `1`. |",
    "| `name` | Required. 1 to 48 characters. |",
    `| \`extends\` | One of ${PRESET_IDS.map((p) => `\`${p}\``).join(", ")}. Default \`plum\`. |`,
    "| `colors`, `radius`, `spacing`, `type`, `size` | Groups, listed below. |",
    "| `tokens` | Any variable from the last table, by name. |",
    "| `variants.light` | The same groups and `tokens`, layered on top in the light appearance. The person picks system, light, or dark in settings. |",
    "",
    "There is no raw CSS field and no motion key. Navigation, menus, and the composer keep 0 ms animation whatever a theme says. A value cannot hold `;`, braces, comments, `url()`, or `var()`.",
    "",
    "A color is any CSS color the browser understands. A length is a number of pixels, or a string with `px`, `rem`, or `em`. A number outside its range is clamped. Anything else is an error that names the key, like `radius.bubble: expected a length, got \"big\"`. A theme with an error is never applied.",
    "",
    "DEVIATION from the plan: `kat.css` has five radius variables, so `radius` has `bubble`, `bubbleTight`, `small`, `row`, `field` instead of panel, menu, button, input, tile, and chip. No variable exists for rail padding, sidebar padding, or the composer height, so the format has no key for them. Reach other variables through `tokens`. `--row-gap` and `--run-gap` are new in `kat.css`, and the message row and bubble read them. `--danger`, `--success`, and `--gold` are read by components but never declared in `kat.css`, so they are transparent until a theme sets them.",
    "",
    "`radius.scale` and `spacing.scale` multiply every length in their group that has a scale (not `radius.field`). They apply to the default or to your value.",
    "",
  ]
  for (const g of GROUPS) {
    out.push(`## ${g}`, "", "| Key | Variable | Range | Default | Notes |", "| --- | --- | --- | --- | --- |")
    for (const f of FIELDS.filter((x) => x.group === g)) {
      const variable = f.variable.endsWith("-scale") ? "(format only)" : `\`${f.variable}\``
      out.push(`| \`${f.key}\` | ${variable} | ${range(f)} | \`${cell(defaultOf(f))}\` | ${cell(f.note ?? "")} |`)
    }
    out.push("")
  }
  out.push(
    "## Tokens",
    "",
    "Every variable below may be set under `tokens` with its own name. The kind says what a value must be. Motion variables are not in the list.",
    "",
    "| Variable | Kind | Default |",
    "| --- | --- | --- |",
  )
  for (const t of knownTokens(css)) out.push(`| \`${t.name}\` | ${t.kind} | \`${cell(t.default)}\` |`)
  out.push("")
  return out.join("\n")
}

if (import.meta.main) {
  writeFileSync(TOKENS_FILE, buildTokensFile())
  writeFileSync(DOC_FILE, buildDoc())
  console.log(`wrote ${TOKENS_FILE}\nwrote ${DOC_FILE}`)
}

export const current = (file: string) => readFileSync(file, "utf8")
