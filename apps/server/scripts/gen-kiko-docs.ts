import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const dir = join(root, "src/agent/kiko-docs")
const entries = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.endsWith(".md"))
  .map((d) => d.name)
  .sort()
  .map((name) => [name, readFileSync(join(dir, name), "utf8")] as const)
export const generated = `// Generated by scripts/gen-kiko-docs.ts from apps/server/src/agent/kiko-docs/*.md. Do not edit.\nexport const KIKO_DOCS: readonly (readonly [string, string])[] = ${JSON.stringify(entries, null, 2)}\n`
if (import.meta.main) writeFileSync(join(root, "src/agent/kiko-docs.gen.ts"), generated)
