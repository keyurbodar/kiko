import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const dir = join(root, "skills")
const entries = readdirSync(dir, { recursive: true, withFileTypes: true })
  .filter((d) => d.isFile())
  .map((d) => join(d.parentPath, d.name).slice(dir.length + 1))
  .sort()
  .map((path) => [path, readFileSync(join(dir, path), "utf8")] as const)
export const generated = `// Generated by scripts/gen-skills.ts from apps/server/skills/**. Do not edit.\nexport const BUILTIN_SKILLS: readonly (readonly [string, string])[] = ${JSON.stringify(entries, null, 2)}\n`
if (import.meta.main) writeFileSync(join(root, "src/skills/builtin.gen.ts"), generated)
