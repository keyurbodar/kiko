import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const root = join(import.meta.dir, "..")
const dir = join(root, "catalog")

function filesOf(folder: string, base = folder): [string, string][] {
  return readdirSync(folder)
    .sort()
    .flatMap((name) => {
      const path = join(folder, name)
      if (statSync(path).isDirectory()) return filesOf(path, base)
      const rel = relative(base, path)
      return rel === "extension.json" ? [] : [[rel, readFileSync(path, "utf8")] as [string, string]]
    })
}

const entries = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const manifest = JSON.parse(readFileSync(join(dir, name, "extension.json"), "utf8"))
    return { name: manifest.name, version: manifest.version, description: manifest.description, bundle: { manifest, files: Object.fromEntries(filesOf(join(dir, name))) } }
  })

export const generated = `// Generated by scripts/gen-catalog.ts from apps/server/catalog/*. Do not edit.\nimport type { ExtensionCatalogEntry } from "@kiko/protocol"\n\nexport const EXTENSION_CATALOG: readonly ExtensionCatalogEntry[] = ${JSON.stringify(entries, null, 2)}\n`
if (import.meta.main) writeFileSync(join(root, "src/user/catalog.gen.ts"), generated)
