/*
 * Built-in recipes live in apps/server/recipes/<slug>/RECIPE.md. This writes the server's copy
 * (the bodies, for installs) and the client's gallery cards (with each icon's svg), so the gallery
 * paints with no request and no icon bundle. Run `bun apps/server/scripts/gen-recipes.ts` after an edit.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { RecipeCard } from "@kiko/protocol"
import { parseRecipe } from "../src/recipes/recipe"
import { pickIcon, toneOf } from "./recipe-icons"

const root = join(import.meta.dir, "..")
const dir = join(root, "recipes")
const phosphor = join(import.meta.dir, "../../../node_modules/@phosphor-icons/core/assets/duotone")

const sources = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => [name, readFileSync(join(dir, name, "RECIPE.md"), "utf8")] as const)

const glyph = (icon: string) =>
  readFileSync(join(phosphor, `${icon}-duotone.svg`), "utf8")
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<rect width="256" height="256" fill="none"\/>/, "")

const cards: RecipeCard[] = sources.map(([name, content]) => {
  const r = parseRecipe(content, name)
  const icon = r.icon ?? pickIcon(r.title, r.description)
  return { slug: r.slug, title: r.title, description: r.description, when: r.when, apps: r.apps, tags: r.tags, icon, glyph: glyph(icon), tone: toneOf(icon) }
})

export const serverGenerated = `// Generated by scripts/gen-recipes.ts from apps/server/recipes/*/RECIPE.md. Do not edit.\nexport const BUILTIN_RECIPES: readonly (readonly [string, string])[] = ${JSON.stringify(sources, null, 2)}\n`
export const clientGenerated = `// Generated by apps/server/scripts/gen-recipes.ts from apps/server/recipes/*/RECIPE.md. Do not edit.\n// Glyphs from Phosphor Icons (@phosphor-icons/core), MIT License, Copyright (c) 2023 Phosphor Icons.\nimport type { RecipeCard } from "@kiko/protocol"\n\nexport const RECIPES: readonly RecipeCard[] = ${JSON.stringify(cards, null, 2)}\n`
export const SERVER_OUT = join(root, "src/recipes/catalog.gen.ts")
export const CLIENT_OUT = join(root, "../web-solid/src/recipes/catalog.gen.ts")

if (import.meta.main) {
  writeFileSync(SERVER_OUT, serverGenerated)
  writeFileSync(CLIENT_OUT, clientGenerated)
  console.log(`${cards.length} recipes: ${cards.map((c) => `${c.slug} (${c.icon})`).join(", ")}`)
}
