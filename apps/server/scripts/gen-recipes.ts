/*
 * Built-in recipes live in apps/server/recipes/<slug>/RECIPE.md. This writes:
 * - src/recipes/icons.gen.ts: the curated Phosphor duotone glyphs, their tones, and their tag words,
 * - src/recipes/catalog.gen.ts: the built-in recipe files, copied into each owner's /home/recipes once,
 * - the client's first-paint gallery cards, before the owner's own list arrives.
 * Run `bun apps/server/scripts/gen-recipes.ts` after an edit.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { icons } from "@phosphor-icons/core"
import type { RecipeCard, RecipeTone } from "@kiko/protocol"
import { EXTRA_ICONS, SYNONYMS } from "../src/recipes/icon-words"
import { parseRecipe } from "../src/recipes/recipe"

const root = join(import.meta.dir, "..")
const dir = join(root, "recipes")
const phosphor = join(import.meta.dir, "../../../node_modules/@phosphor-icons/core/assets/duotone")

const TONES: Record<string, RecipeTone> = {
  finances: "green", commerce: "green", nature: "green", communications: "blue", "maps & travel": "teal", weather: "amber",
  objects: "orange", media: "pink", design: "pink", games: "violet", "health & wellness": "red", people: "violet",
  office: "amber", "technology & development": "slate", brands: "slate",
}

const stem = (w: string) => w.replace(/ies$/, "y").replace(/(ing|ers|es|s|ed)$/, "")
const glyph = (icon: string) =>
  readFileSync(join(phosphor, `${icon}-duotone.svg`), "utf8")
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<rect width="256" height="256" fill="none"\/>/, "")

const names = [...new Set([...Object.values(SYNONYMS), ...EXTRA_ICONS])].sort()
const table = Object.fromEntries(
  names.map((name) => {
    const found = icons.find((i) => i.name === name)
    if (!found) throw new Error(`no Phosphor icon named ${name}`)
    const tone = found.categories.map((c) => TONES[c]).find(Boolean) ?? "slate"
    const words = [...new Set(found.tags.flatMap((t) => t.toLowerCase().split(/[^a-z]+/)).filter((w) => w.length > 2).map(stem))].sort()
    return [name, { glyph: glyph(name), tone, words }]
  }),
)

const sources = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => [name, readFileSync(join(dir, name, "RECIPE.md"), "utf8")] as const)

export const iconsGenerated = `// Generated by scripts/gen-recipes.ts. Do not edit.\n// Glyphs from Phosphor Icons (@phosphor-icons/core), MIT License, Copyright (c) 2023 Phosphor Icons.\nimport type { IconInfo } from "./icons"\n\nexport const ICONS: Record<string, IconInfo> = ${JSON.stringify(table)}\n`
export const serverGenerated = `// Generated by scripts/gen-recipes.ts from apps/server/recipes/*/RECIPE.md. Do not edit.\nexport const BUILTIN_RECIPES: readonly (readonly [string, string])[] = ${JSON.stringify(sources, null, 2)}\n`
export const SERVER_OUT = join(root, "src/recipes/catalog.gen.ts")
export const ICONS_OUT = join(root, "src/recipes/icons.gen.ts")
export const CLIENT_OUT = join(root, "../web-solid/src/recipes/catalog.gen.ts")

/** The client's cards come from the same function the Worker uses, so first paint and the live list agree. */
export async function clientGenerated(): Promise<string> {
  const { recipeCard } = await import("../src/recipes/card")
  const cards: RecipeCard[] = sources.map(([name, content]) => recipeCard(parseRecipe(content, name), false, null))
  return `// Generated by apps/server/scripts/gen-recipes.ts from apps/server/recipes/*/RECIPE.md. Do not edit.\n// Glyphs from Phosphor Icons (@phosphor-icons/core), MIT License, Copyright (c) 2023 Phosphor Icons.\nimport type { RecipeCard } from "@kiko/protocol"\n\nexport const RECIPES: readonly RecipeCard[] = ${JSON.stringify(cards, null, 2)}\n`
}

if (import.meta.main) {
  writeFileSync(ICONS_OUT, iconsGenerated)
  writeFileSync(SERVER_OUT, serverGenerated)
  writeFileSync(CLIENT_OUT, await clientGenerated())
  console.log(`${names.length} icons, ${sources.length} recipes`)
}
